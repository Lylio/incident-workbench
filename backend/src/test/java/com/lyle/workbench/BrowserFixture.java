package com.lyle.workbench;

import static com.lyle.workbench.Model.*;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.List;
import org.springframework.boot.SpringApplication;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Primary;

/** Development verification harness only; excluded from the production JAR and Docker runtime. */
public class BrowserFixture {
  public static void main(String[] args) {
    SpringApplication app = new SpringApplication(WorkbenchApplication.class, FixtureConfig.class);
    app.setAdditionalProfiles("test");
    app.run(args);
  }

  @TestConfiguration
  static class FixtureConfig {
    @Bean
    @Primary
    Analyst browserAnalyst(ObjectMapper mapper) {
      return new Analyst() {
        public boolean available() {
          return true;
        }

        public String model() {
          return "LOCAL-TEST-FIXTURE-NOT-A-LIVE-MODEL";
        }

        public Draft analyze(String prompt) {
          try {
            var entries = mapper.readTree(prompt).path("providedEvidence");
            String id = entries.get(0).path("id").asText();
            return new Draft(
                "TEST FIXTURE: This response verifies the UI and persistence flow; it is not an AI"
                    + " investigation.",
                List.of(
                    new Hypothesis(
                        "Test hypothesis: examine the dependency",
                        "Illustrative fixture text only. Inspect the selected evidence before"
                            + " drawing a conclusion.",
                        List.of(id))),
                List.of("Inspect dependency connectivity", "Compare configuration history"),
                List.of("This result was generated by a local test fixture, not OpenAI."));
          } catch (Exception e) {
            throw new IllegalStateException(e);
          }
        }
      };
    }
  }
}
